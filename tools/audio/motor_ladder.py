#!/usr/bin/env python3
"""Motor-sound ladder of the fpvcore mod: closed-form pitch/volume curves and the tables derived from them.

No audio is read here. The motor sound is built from three component layers (low "idle" hum, "mid" motor whine, "high" prop noise).
A sound parameter T in 0..0.7 (0 = idle, 0.7 = full-throttle on the fastest preset) sets the playback pitch and volume of every
component through the simple curves below. The ladder turns that into K pre-rendered snapshot layers of the *whole* drone sound at
anchor values of T; Minecraft plays all K layers at once, each at a pitch within 0.7..1.4 (inside its 0.5..2.0 clamp), and
cross-fades them equal-power while the level follows the loudness curve.

Run directly to (re)write adapters/minecraft-fabric/src/main/java/dev/fpvcore/mc/MotorCurves.java.
"""
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
JAVA_OUT = ROOT / "adapters/minecraft-fabric/src/main/java/dev/fpvcore/mc/MotorCurves.java"
RMS = (0.02, 0.03, 0.09)                 # relative loudness weights of the idle / mid / high component layers
T_STEP, T_MAX = 0.01, 0.70
RHO = 1.4                                # ratio of the dominant sound rate between neighbouring ladder layers
XF = (0.25, 0.75)                        # crossfade happens in this part of each ladder interval


def cue(T):
    """((pitch idle, mid, high), (vol idle, mid, high)) for sound parameter T. Cubic pitch curves, bell/linear/quadratic volume curves."""
    p_idle = ((2.513 * T - 1.48) * T + 1.024) * T + 0.39
    p_mid = ((9.247 * T - 6.608) * T + 4.514) * T + 0.657
    p_high = 0.75 * p_mid
    v_idle = max(0.0, 1.0 - (T / 0.3) ** 2)
    v_mid = 3.85 * T
    v_high = 0.13 + 2.0 * T + 0.7 * T * T
    return (p_idle, p_mid, p_high), (v_idle, v_mid, v_high)


def sound_curve(x):
    """Throttle (rpm fraction) -> sound parameter scale: a power law."""
    return min(max(x, 0.0), 1.0) ** 1.72


def level(T):
    """Overall loudness at T (uncorrelated layers)."""
    _, v = cue(T)
    return float(np.sqrt(sum((vi * r) ** 2 for vi, r in zip(v, RMS))))


def rate(T):
    """Dominant sound rate: energy-weighted geometric mean of the playback pitches (monotone in T)."""
    p, v = cue(T)
    e = np.array([(vi * r) ** 2 for vi, r in zip(v, RMS)])
    return float(np.exp((e * np.log(p)).sum() / e.sum()))


def grid():
    return np.round(np.arange(0, T_MAX + 1e-9, T_STEP), 6)


def anchors():
    """Anchor T values T_k and rates r_k = r(0) * RHO^k covering r(0)..r(T_MAX) with pitch ratios <= RHO."""
    g = grid(); r = np.array([rate(t) for t in g])
    r0, rmax = r[0], r[-1]
    K = 1
    while r0 * RHO ** (K - 1) * RHO < rmax * 0.999: K += 1
    rk = r0 * RHO ** np.arange(K)
    Tk = np.interp(rk, r, g)
    return Tk, rk


def smooth(a, b, x):
    t = min(max((x - a) / (b - a), 0.0), 1.0); return t * t * (3 - 2 * t)


def tables():
    """pitch[K][G], vol[K][G] (w_k * level(T)/level(T_REF)), the ladder weights and anchors."""
    g = grid(); Tk, rk = anchors(); K = len(rk)
    d = np.log(RHO)
    pitch = np.ones((K, len(g))); vol = np.zeros((K, len(g)))
    lref = level(0.62)
    for gi, T in enumerate(g):
        x = np.log(rate(T) / rk[0]) / d          # position in ladder units
        w = np.zeros(K)
        if x >= K - 1: w[K - 1] = 1.0
        elif x <= 0: w[0] = 1.0
        else:
            k = int(np.floor(x)); s = smooth(XF[0], XF[1], x - k)
            w[k] = np.cos(np.pi / 2 * s); w[k + 1] = np.sin(np.pi / 2 * s)
        for k in range(K):
            pitch[k, gi] = min(max(rate(T) / rk[k], 0.7), 1.4)
            vol[k, gi] = w[k] * level(T) / lref
    return g, Tk, rk, pitch, vol


def write_java():
    g, Tk, rk, pitch, vol = tables(); K = len(rk)
    def arr(m): return ",\n".join("        {" + ", ".join(f"{v:.4f}f" for v in row) + "}" for row in m)
    src = f"""package dev.fpvcore.mc;

/** GENERATED by tools/audio/motor_ladder.py (do not edit). Layer ladder of the motor sound: for the sound parameter T
 *  (0..{T_MAX}) in steps of {T_STEP}: pitch and volume (equal-power crossfade x level curve, 1.0 = level at T=0.62)
 *  of the {K} bundled layers motor_1..motor_{K}. Anchor T of the layers: {", ".join(f"{t:.3f}" for t in Tk)}. */
final class MotorCurves {{
    private MotorCurves() {{}}
    static final int LAYERS = {K};
    static final float T_STEP = {T_STEP}f;
    static final float[][] PITCH = {{
{arr(pitch)}
    }};
    static final float[][] VOL = {{
{arr(vol)}
    }};
}}
"""
    JAVA_OUT.write_text(src)
    print("wrote", JAVA_OUT, "K =", K, "anchors T", np.round(Tk, 3), "rates", np.round(rk, 2))


if __name__ == "__main__":
    write_java()
