#!/usr/bin/env python3
"""Render the drone sound track of a recorded demo take offline (original CC0 sounds only).

Reads <take>.csv written by DemoRecorder (one row per video frame: frame, t, armed, rpm, throttle, speed, impulse, angRate, wingRpm, wingDist, x, y, z) and mixes the
mod's own sound layers (adapters/minecraft-fabric/src/main/resources/assets/fpvcore/sounds/*.ogg, generated by tools/audio/synth_drone.py) exactly like the in-game
MotorModel / MotorLayerSound / WindSound / FlipSound / DroneAudio.crash do (same pitch/volume tables from MotorCurves.java, same update rate of 20 Hz).

usage: render_audio.py <take.csv> <out.wav> [preset=5race]
"""
import re, subprocess, sys
import numpy as np

SR = 44100
ROOT = __file__.rsplit('/tools/demo/', 1)[0]
MC = ROOT + '/adapters/minecraft-fabric/src/main/'
SND = MC + 'resources/assets/fpvcore/sounds/'
RPM_MAX = {'5race': 32290.0, '5freestyle': 31576.0, 'KM': 47330.0, '7Msurfer': 24743.0}
T_FULL = {'5race': 0.620, '5freestyle': 0.571, 'KM': 0.631, '7Msurfer': 0.489}
GAIN, OTHER = 0.8, 0.6


def load(name):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', SND + name + '.ogg', '-f', 'f32le', '-ac', '1', '-ar', str(SR), '-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32).astype(np.float64)


def curves():
    src = open(MC + 'java/dev/fpvcore/mc/MotorCurves.java').read()
    def arr(name):
        body = re.search(name + r' = \{\s*(.*?)\n    \};', src, re.S).group(1)
        rows = re.findall(r'\{([^{}]*)\}', body)
        return np.array([[float(x.replace('f', '')) for x in r.split(',')] for r in rows])
    return arr('PITCH'), arr('VOL')


PITCH, VOL = curves()
T_STEP = 0.01


def sound_curve(x):
    x = np.clip(x, 0, 1)
    return np.where(x < 0.3, x / 0.3 * 0.125, 0.125 + (x - 0.3) / 0.7 * 0.875)


def layer_params(n, tfull):
    t = np.clip(tfull * sound_curve(np.minimum(n, 1.1)), 0, (PITCH.shape[1] - 1) * T_STEP)
    f = t / T_STEP
    i = np.minimum(f.astype(int), PITCH.shape[1] - 2)
    a = f - i
    p = PITCH[:, i] * (1 - a) + PITCH[:, i + 1] * a
    v = VOL[:, i] * (1 - a) + VOL[:, i + 1] * a
    return np.clip(p, 0.5, 2.0), v   # (6, ticks)


def upsample(x, ticks_t, t_audio):
    return np.interp(t_audio, ticks_t, x)


def loop_play(buf, pitch, vol):
    """Loop buf at a varying playback rate (pitch array per output sample) with gain vol."""
    pos = np.cumsum(pitch) % len(buf)
    i = pos.astype(np.int64)
    f = pos - i
    j = (i + 1) % len(buf)
    return (buf[i] * (1 - f) + buf[j] * f) * vol


def main():
    csv, out = sys.argv[1], sys.argv[2]
    preset = sys.argv[3] if len(sys.argv) > 3 else '5race'
    d = np.loadtxt(csv, delimiter=',')
    fps = 60.0
    nfr = len(d)
    dur = nfr / fps + 0.5
    t_audio = np.arange(int(dur * SR)) / SR
    # per client tick state (20 Hz)
    tick_t = np.arange(0, dur, 0.05)
    fr = np.minimum((tick_t * fps).astype(int), nfr - 1)
    armed = d[fr, 2] > 0.5
    rpm = d[fr, 3]
    speed = d[fr, 5]
    angr = d[fr, 7]
    wrpm = d[fr, 8]; wdist = d[fr, 9]
    def motor_n(rpm, armed):
        n = 0.0; out = np.zeros(len(rpm))
        for k in range(len(rpm)):
            target = min(max(rpm[k] / RPM_MAX[preset], 0), 1.1) if armed[k] else 0.0
            interp = n + (target - n) * min(max(0.05 * 10, 0), 1)
            n = max(interp, target); out[k] = n
        return out
    mix = np.zeros(len(t_audio))
    layers = [load('motor_%d' % (i + 1)) for i in range(6)]
    def motor(rpmv, armv, scale, att=None):
        n = motor_n(rpmv, armv)
        p, v = layer_params(n, T_FULL[preset])
        o = np.zeros(len(t_audio))
        for k in range(6):
            vol = np.where(armv, np.minimum(v[k] * GAIN * scale, 1.0), 0.0)
            if att is not None: vol = vol * att
            o += loop_play(layers[k], upsample(p[k], tick_t, t_audio), upsample(vol, tick_t, t_audio))
        return o
    mix += motor(rpm, armed, 1.0)
    if wrpm.max() > 0:   # second pilot's drone: positional, linear falloff over 48 m
        warm = wrpm > 1000
        att = np.clip(1 - wdist / 48.0, 0, 1) ** 1.5
        mix += motor(wrpm, warm, OTHER, att)
    # wind
    kmh = speed * 3.6
    k = np.clip(kmh * kmh / 15000.0, 0, 1)
    for name, w in (('wind_low', 1.2), ('wind_high', 0.5)):
        b = load(name)
        vol = np.where(armed, 0.65 * k * 0.6 * w * 0.5, 0.0)
        mix += loop_play(b, upsample(0.8 + 1.1 * k, tick_t, t_audio), upsample(vol, tick_t, t_audio))
    # flip whoosh
    rate = 0.0; rs = np.zeros(len(angr))
    for i in range(len(angr)):
        rate += (angr[i] - rate) * 0.3; rs[i] = rate
    kf = np.clip((rs - 250.0) / 900.0, 0, 1)
    b = load('flip')
    mix += loop_play(b, upsample(0.8 + 0.7 * kf, tick_t, t_audio), upsample(np.where(armed, kf * 0.55, 0.0), tick_t, t_audio))
    # crashes (impulse edge > 50)
    imp = d[:, 6]
    last = -1.0
    rng = np.random.default_rng(7)
    for i in range(nfr):
        if imp[i] > 50 and (i / fps - last) > 0.35:
            last = i / fps
            v = (imp[i] - 100) / 1900.0
            if v <= 0.01:
                s = load('prop_strike_%d' % (1 + int(rng.integers(0, 2)))); g = min((imp[i] - 50) / 50.0, 1) * 0.6
            else:
                s = load(('crash_big_%d' % (1 + int(rng.integers(0, 2)))) if imp[i] > 1500 else ('crash_%d' % (1 + int(rng.integers(0, 3))))); g = min(1.0, v * (0.9 + 0.5 * rng.random()))
            a = int(last * SR); e = min(len(mix), a + len(s))
            mix[a:e] += s[:e - a] * g
    # soft limiter
    mix = np.tanh(mix * 1.1) / np.tanh(1.1)
    st = np.stack([mix, mix], axis=1).astype(np.float32)
    raw = (np.clip(st, -1, 1) * 32767).astype('<i2').tobytes()
    subprocess.run(['ffmpeg', '-y', '-v', 'error', '-f', 's16le', '-ar', str(SR), '-ac', '2', '-i', '-', out], input=raw, check=True)
    print('wrote', out, '%.1f s' % dur, 'peak %.2f' % np.abs(mix).max())

if __name__ == '__main__':
    main()
